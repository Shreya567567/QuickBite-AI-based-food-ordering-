export const getFoodItemsForRestaurant = (restaurantName) => {
  const nameLower = restaurantName.toLowerCase();
  
  // 1. Check if we have items explicitly assigned to this restaurant in the array
  const explicitItems = indianFoodItems.filter(item => 
    item.restaurant.toLowerCase() === nameLower ||
    (item.restaurant.toLowerCase().includes("domino") && nameLower.includes("domino")) ||
    (item.restaurant.toLowerCase().includes("kfc") && nameLower.includes("kfc")) ||
    (item.restaurant.toLowerCase().includes("pizza hut") && nameLower.includes("pizza hut")) ||
    (item.restaurant.toLowerCase().includes("harilal") && nameLower.includes("harilal")) ||
    (item.restaurant.toLowerCase().includes("pramod") && nameLower.includes("pramod")) ||
    (item.restaurant.toLowerCase().includes("chappan bhog") && nameLower.includes("chappan bhog"))
  );
  
  if (explicitItems.length > 0) {
    return explicitItems.map(item => ({
      ...item,
      restaurant: restaurantName
    }));
  }
  
  // 2. Otherwise fall back to existing keyword categories
  let matchingItems = [];
  
  if (nameLower.includes("biryani")) {
    matchingItems = indianFoodItems.filter(item => item.category === "Biryani");
  } else if (nameLower.includes("burger")) {
    matchingItems = indianFoodItems.filter(item => item.category === "Burger");
  } else if (nameLower.includes("dosa") || nameLower.includes("south")) {
    matchingItems = indianFoodItems.filter(item => item.category === "South Indian");
  } else if (nameLower.includes("pizza") || nameLower.includes("bistro") || nameLower.includes("italian")) {
    matchingItems = indianFoodItems.filter(item => item.category === "Pizza");
  } else if (nameLower.includes("momo")) {
    matchingItems = indianFoodItems.filter(item => item.category === "Momos");
  } else if (nameLower.includes("noodle") || nameLower.includes("chinese") || nameLower.includes("nest")) {
    matchingItems = indianFoodItems.filter(item => item.category === "Chinese");
  } else if (nameLower.includes("sweet") || nameLower.includes("dessert") || nameLower.includes("magic")) {
    matchingItems = indianFoodItems.filter(item => item.category === "Desserts");
  } else if (nameLower.includes("chai") || nameLower.includes("cafe") || nameLower.includes("beverage")) {
    matchingItems = indianFoodItems.filter(item => item.category === "Beverages");
  } else if (nameLower.includes("roll")) {
    matchingItems = indianFoodItems.filter(item => item.category === "Rolls");
  } else if (nameLower.includes("punjab") || nameLower.includes("dhaba") || nameLower.includes("indian")) {
    matchingItems = indianFoodItems.filter(item => item.category === "Main Course" || item.category === "Starters");
  }

  // If no direct keyword match, deterministically assign items based on name hash
  if (matchingItems.length === 0) {
    let hash = 0;
    for (let i = 0; i < restaurantName.length; i++) {
      hash = restaurantName.charCodeAt(i) + ((hash << 5) - hash);
    }
    hash = Math.abs(hash);
    
    // Select 6-8 random-ish but deterministic items
    matchingItems = indianFoodItems.filter((_, idx) => (idx + hash) % 5 === 0);
  }

  // Overwrite the restaurant field in each item so the UI displays the correct restaurant name!
  return matchingItems.map(item => ({
    ...item,
    restaurant: restaurantName
  }));
};
